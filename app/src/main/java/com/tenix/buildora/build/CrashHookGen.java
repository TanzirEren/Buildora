package com.tenix.buildora.build;

import com.tenix.buildora.core.FileUtil;

import java.io.File;
import java.io.IOException;

/**
 * Debug builds get a tiny ContentProvider that installs an uncaught-exception handler and sends the stack trace to Buildora,
 * so a crash of the app you just built shows up in Buildora's Logcat screen without any special permission.
 */
public final class CrashHookGen {
    private CrashHookGen() {}

    public static final String ACTION = "com.tenix.buildora.CRASH";

    public static File writeSource(File genDir) throws IOException {
        String src =
                "package buildora.rt;\n\n" +
                "import android.content.ContentProvider;\n" +
                "import android.content.ContentValues;\n" +
                "import android.content.Context;\n" +
                "import android.content.Intent;\n" +
                "import android.database.Cursor;\n" +
                "import android.net.Uri;\n\n" +
                "/** Generated by Buildora (debug builds only): reports crashes to the Buildora app. */\n" +
                "public class CrashHook extends ContentProvider {\n" +
                "    @Override public boolean onCreate() {\n" +
                "        final Context ctx = getContext();\n" +
                "        final Thread.UncaughtExceptionHandler prev = Thread.getDefaultUncaughtExceptionHandler();\n" +
                "        Thread.setDefaultUncaughtExceptionHandler(new Thread.UncaughtExceptionHandler() {\n" +
                "            @Override public void uncaughtException(Thread t, Throwable e) {\n" +
                "                try {\n" +
                "                    java.io.StringWriter sw = new java.io.StringWriter();\n" +
                "                    e.printStackTrace(new java.io.PrintWriter(sw));\n" +
                "                    String s = sw.toString();\n" +
                "                    if (s.length() > 60000) s = s.substring(0, 60000);\n" +
                "                    Intent i = new Intent(\"" + ACTION + "\");\n" +
                "                    i.setPackage(\"com.tenix.buildora\");\n" +
                "                    i.putExtra(\"pkg\", ctx.getPackageName());\n" +
                "                    i.putExtra(\"thread\", t.getName());\n" +
                "                    i.putExtra(\"time\", System.currentTimeMillis());\n" +
                "                    i.putExtra(\"trace\", s);\n" +
                "                    ctx.sendBroadcast(i);\n" +
                "                } catch (Throwable ignored) { }\n" +
                "                if (prev != null) prev.uncaughtException(t, e);\n" +
                "            }\n" +
                "        });\n" +
                "        return true;\n" +
                "    }\n" +
                "    @Override public Cursor query(Uri u, String[] p, String s, String[] a, String o) { return null; }\n" +
                "    @Override public String getType(Uri u) { return null; }\n" +
                "    @Override public Uri insert(Uri u, ContentValues v) { return null; }\n" +
                "    @Override public int delete(Uri u, String s, String[] a) { return 0; }\n" +
                "    @Override public int update(Uri u, ContentValues v, String s, String[] a) { return 0; }\n" +
                "}\n";
        File f = new File(genDir, "buildora/rt/CrashHook.java");
        FileUtil.writeText(f, src);
        return f;
    }

    public static void writeManifest(File out) throws IOException {
        FileUtil.writeText(out,
                "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n" +
                "<manifest xmlns:android=\"http://schemas.android.com/apk/res/android\" package=\"buildora.rt\">\n" +
                "    <queries><package android:name=\"com.tenix.buildora\" /></queries>\n" +
                "    <application>\n" +
                "        <provider android:name=\"buildora.rt.CrashHook\" android:authorities=\"${applicationId}.buildora.crash\" android:exported=\"false\" />\n" +
                "    </application>\n" +
                "</manifest>\n");
    }
}
